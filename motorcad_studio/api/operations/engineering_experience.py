    def project_engineer_journey(self, project_id: str):
        try:
            return self.engineer_journey.journey(project_id)
        except KeyError as exc:
            raise HTTPException(status_code=404, detail='项目不存在') from exc

    def project_engineering_decision_cockpit(self, project_id: str):
        try:
            return self.engineer_journey.decision_cockpit(project_id)
        except KeyError as exc:
            raise HTTPException(status_code=404, detail='项目不存在') from exc
